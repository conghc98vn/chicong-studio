import assert from 'node:assert/strict';
import {mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {createApp} from '../server/app.mjs';

const pw = await import(process.env.STUDIO_PLAYWRIGHT_MODULE || 'playwright');
const dir = await mkdtemp(path.join(tmpdir(), 'album-password-form-'));
const fixture = await createApp({dataDir: dir, env: {}, seed: false});
const server = fixture.app.listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const base = 'http://127.0.0.1:' + server.address().port;
let browser;
try {
  browser = await pw.chromium.launch({channel: 'chrome', headless: true});
  const context = await browser.newContext();
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const request = (url, data) => context.request.post(base + url, {headers: {Origin: base}, data});
  assert.equal((await request('/api/admin/setup', {email: 'password-form@example.test', password: 'fixture-password-123'})).status(), 201);
  await page.goto(base + '/admin');
  await page.getByRole('button', {name: 'Tạo bộ ảnh', exact: true}).click();
  const form = page.locator('[data-form=album]');
  const password = form.locator('[name=password]');
  await form.locator('[name=title]').fill('Kiểm tra mật khẩu');
  await form.locator('[name=status]').selectOption('private');
  await password.pressSequentially('short');
  assert.equal(await password.evaluate(input => input.validity.tooShort), true);
  await form.locator('[name=status]').selectOption('draft');
  assert.equal(await form.evaluate(form => form.checkValidity()), true, 'a hidden password must not block saving a draft');
  assert.equal(await password.isDisabled(), true);
  assert.equal(await form.evaluate(form => new FormData(form).has('password')), false);
  await form.locator('[name=status]').selectOption('private');
  assert.equal(await password.isEnabled(), true);
  await password.fill('');
  assert.equal(await password.evaluate(input => input.validity.valueMissing), true, 'a new protected album needs a password');
  assert.match(await password.getAttribute('placeholder'), /Ít nhất 8/);
  await form.locator('[name=require_password]').uncheck();
  assert.equal(await form.evaluate(form => form.checkValidity()), true);
  await form.getByRole('button', {name: 'Tạo bộ ảnh', exact: true}).click();
  await page.locator('.badge.no-password').waitFor();
  await page.locator('[data-action=album-settings]').click();
  await form.locator('[name=require_password]').check();
  assert.equal(await password.evaluate(input => input.validity.valueMissing), true, 'adding protection to an existing album requires a password');
  await password.fill('client-password-123');
  await form.getByRole('button', {name: 'Lưu thay đổi', exact: true}).click();
  await page.locator('.badge.has-password').waitFor();
  await page.locator('[data-action=album-settings]').click();
  assert.equal(await password.inputValue(), '');
  assert.equal(await password.evaluate(input => input.required), false, 'an existing password can be retained');
  assert.match(await password.getAttribute('placeholder'), /giữ mật khẩu hiện tại/);
  await form.getByRole('button', {name: 'Lưu thay đổi', exact: true}).click();
  await page.locator('#editor').waitFor({state: 'hidden'});
  const link = await page.locator('.album-detail-top a[href^="/gallery/"]').getAttribute('href');
  const guest = await (await browser.newContext()).newPage();
  await guest.goto(base + link);
  await guest.getByLabel('Mật khẩu bộ ảnh', {exact: true}).fill('client-password-123');
  await guest.getByRole('button', {name: 'Mở bộ ảnh', exact: true}).click();
  await guest.locator('.client-toolbar').waitFor();
  assert.deepEqual(errors, []);
  console.log('PASS: Hidden password validation, new/existing password requirements, and retaining password after save');
} finally {
  await browser?.close();
  server.closeAllConnections();
  await new Promise(resolve => server.close(resolve));
  await fixture.photoCleanup.close();
  await fixture.db.close();
  await rm(dir, {recursive: true, force: true});
}
